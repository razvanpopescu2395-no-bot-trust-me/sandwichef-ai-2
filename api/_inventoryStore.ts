import { Redis } from '@upstash/redis';

export interface BreadInventoryLog {
  id: string;
  timestamp: string;
  timeFormatted: string;
  type: 'sale' | 'physical' | 'reset' | 'adjustment';
  quantity: number;
  seller?: string;
  note: string;
}

export interface BreadInventoryState {
  date: string;
  dailyTarget: number;
  totalPhysicalSold: number;
  totalOnlineSold: number;
  remaining: number;
  isSoldOut: boolean;
  lastUpdated: string;
  logs: BreadInventoryLog[];
}

export const REDIS_KEY = 'sandwichef_bread_inventory';

export function getTodayDateString(): string {
  const now = new Date();
  return now.toISOString().split('T')[0];
}

export function getBucharestTimeFormatted(): string {
  return new Intl.DateTimeFormat('ro-RO', {
    timeZone: 'Europe/Bucharest',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  }).format(new Date());
}

export function getDefaultState(): BreadInventoryState {
  return {
    date: getTodayDateString(),
    dailyTarget: 12,
    totalPhysicalSold: 0,
    totalOnlineSold: 0,
    remaining: 12,
    isSoldOut: false,
    lastUpdated: new Date().toISOString(),
    logs: [
      {
        id: `init-${Date.now()}`,
        timestamp: new Date().toISOString(),
        timeFormatted: getBucharestTimeFormatted(),
        type: 'reset',
        quantity: 12,
        note: 'Inițializare lot zilnic (12 panini Schiacciata)',
        seller: 'Sistem',
      },
    ],
  };
}

let memoryState: BreadInventoryState = getDefaultState();
let redisInstance: Redis | null = null;

export function getRedis(): Redis | null {
  if (redisInstance) return redisInstance;

  // Support all variable names generated by Vercel Upstash integration
  const url =
    process.env.UPSTASH_REDIS_REST_KV_REST_API_URL ||
    process.env.UPSTASH_REDIS_REST_URL ||
    process.env.KV_REST_API_URL;
  const token =
    process.env.UPSTASH_REDIS_REST_KV_REST_API_TOKEN ||
    process.env.UPSTASH_REDIS_REST_TOKEN ||
    process.env.KV_REST_API_TOKEN;

  if (url && token) {
    redisInstance = new Redis({ url, token });
    return redisInstance;
  }

  try {
    redisInstance = Redis.fromEnv();
    return redisInstance;
  } catch (e) {
    return null;
  }
}

export function isRedisConfigured(): boolean {
  return getRedis() !== null;
}

export const isVercelKvConfigured = isRedisConfigured;

export async function getInventoryState(): Promise<BreadInventoryState> {
  const today = getTodayDateString();
  const redis = getRedis();

  if (redis) {
    try {
      const data = await redis.get<BreadInventoryState>(REDIS_KEY);
      if (data && typeof data === 'object' && typeof data.remaining === 'number') {
        if (data.date !== today) {
          const fresh = getDefaultState();
          await saveInventoryState(fresh);
          return fresh;
        }
        return data;
      }
    } catch (e) {
      console.error('[Upstash Redis Read Error]:', e);
    }
  }

  // Fallback to memory
  if (memoryState.date !== today) {
    memoryState = getDefaultState();
  }
  return memoryState;
}

export async function saveInventoryState(state: BreadInventoryState): Promise<BreadInventoryState> {
  state.lastUpdated = new Date().toISOString();
  state.isSoldOut = state.remaining <= 0;
  memoryState = state;

  const redis = getRedis();
  if (redis) {
    try {
      await redis.set(REDIS_KEY, state);
    } catch (e) {
      console.error('[Upstash Redis Write Error]:', e);
    }
  }

  return state;
}
